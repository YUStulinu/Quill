//! The native backend: instruction selection, register allocation and assembly emission for x86-64.

pub mod emit;
pub mod isel;
pub mod regalloc;
pub mod x86;

use std::fmt::Write as _;

use crate::ir::{FuncId, Module};
use x86::Abi;

/// Assembly symbol names for everything the program refers to.
pub struct Symbols {
    funcs: Vec<String>,
}

impl Symbols {
    pub fn new(m: &Module) -> Symbols {
        let funcs = m
            .funcs
            .iter()
            .enumerate()
            .map(|(i, f)| {
                let clean: String = f.name.chars().map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' }).collect();
                format!("qf{i}_{clean}")
            })
            .collect();
        Symbols { funcs }
    }

    pub fn func(&self, f: FuncId) -> String {
        self.funcs[f as usize].clone()
    }

    pub fn closure(&self, f: FuncId) -> String {
        format!("qc{f}")
    }

    pub fn string(&self, s: u32) -> String {
        format!("qs{s}")
    }

    pub fn ctor0(&self, c: u32) -> String {
        format!("qk{c}")
    }
}

/// Machine-level statistics, for `quill build --stats`.
#[derive(Default, Debug)]
pub struct CodegenStats {
    pub functions: usize,
    pub instructions: usize,
    pub spilled: usize,
}

/// Compiles a whole module to an assembly file (GNU assembler, Intel syntax).
/// Generates assembly for a module. `optimize` turns on the machine-level optimizations (division by
/// constants without `idiv`, inline array and string accesses); without it the output is a plain
/// translation, which keeps `-O0` a meaningful baseline.
pub fn compile(m: &Module, abi: Abi, optimize: bool) -> (String, CodegenStats) {
    let syms = Symbols::new(m);
    let mut out = String::new();
    let mut stats = CodegenStats::default();
    let _ = writeln!(out, "# Generated by the Quill compiler.");
    let _ = writeln!(out, "    .intel_syntax noprefix");
    let _ = writeln!(out, "    .text");
    for (i, f) in m.funcs.iter().enumerate() {
        if f.rpo().len() == 1 && matches!(f.blocks[f.entry as usize].term, crate::ir::Term::Unreachable) {
            continue;
        }
        let mf = isel::select(m, i, abi, &syms, optimize);
        let alloc = regalloc::allocate(&mf, abi);
        stats.functions += 1;
        stats.instructions += mf.blocks.iter().map(|b| b.insts.len()).sum::<usize>();
        stats.spilled += alloc.slots as usize;
        let alias = if i as FuncId == m.main { Some("quill_main") } else { None };
        emit::emit_function(&mut out, &mf, &alloc, abi, alias);
    }
    emit_data(&mut out, m, &syms);
    (out, stats)
}

fn emit_data(out: &mut String, m: &Module, syms: &Symbols) {
    let _ = writeln!(out, "\n    .data");
    for (i, s) in m.strings.iter().enumerate() {
        let bytes = s.as_bytes();
        let _ = writeln!(out, "    .p2align 3");
        let _ = writeln!(out, "{}:", syms.string(i as u32));
        let _ = writeln!(out, "    .quad {}", isel::header(isel::KIND_STRING, 0, bytes.len() as u32));
        for chunk in bytes.chunks(32) {
            let list: Vec<String> = chunk.iter().map(|b| b.to_string()).collect();
            let _ = writeln!(out, "    .byte {}", list.join(", "));
        }
        let _ = writeln!(out, "    .byte 0");
    }
    for (i, c) in m.ctor0.iter().enumerate() {
        let _ = writeln!(out, "    .p2align 3");
        let _ = writeln!(out, "{}:  # {}", syms.ctor0(i as u32), c.name);
        let _ = writeln!(out, "    .quad {}", isel::header(isel::KIND_FIELDS, c.tag, 0));
    }
    // A static closure (no captures) for every function that takes an environment.
    for (i, f) in m.funcs.iter().enumerate() {
        if f.takes_env {
            let _ = writeln!(out, "    .p2align 3");
            let _ = writeln!(out, "{}:  # {}", syms.closure(i as u32), f.name);
            let _ = writeln!(out, "    .quad {}", isel::header(isel::KIND_CLOSURE, 0, 1));
            let _ = writeln!(out, "    .quad {}", syms.func(i as u32));
        }
    }
}
